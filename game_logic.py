def calculate_level(xp: int) -> int:
    """هر 100 تجربه یک سطح."""
    return max(1, xp // 100 + 1)


def get_mission_reward(correct_count: int) -> dict:
    """پاداش مأموریت بر اساس پاسخ‌ها."""
    total = len(MISSION["steps"])
    correct_count = max(0, min(correct_count, total))

    xp = 10 * correct_count
    coins = 5 * correct_count

    # پاداش تکمیل مأموریت
    if correct_count == total:
        xp += MISSION["reward_xp"]
        coins += MISSION["reward_coins"]

    return {
        "xp": xp,
        "coins": coins,
        "completed": correct_count == total,
    }
